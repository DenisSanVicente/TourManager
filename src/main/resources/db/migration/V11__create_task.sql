
CREATE TABLE task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artistic_project_id BIGINT NOT NULL,
    concert_id BIGINT,
    tour_id BIGINT,
    created_by_membership_id BIGINT NOT NULL,
    assigned_to_membership_id BIGINT,
    title VARCHAR(150) NOT NULL,
    description TEXT,
    status VARCHAR(30) NOT NULL,
    due_date DATE,
    created_at TIMESTAMP NOT NULL,

    FOREIGN KEY (artistic_project_id) REFERENCES artistic_project(id),
    FOREIGN KEY (concert_id) REFERENCES concert(id),
    FOREIGN KEY (tour_id) REFERENCES tour(id),
    FOREIGN KEY (created_by_membership_id) REFERENCES project_membership(id),
    FOREIGN KEY (assigned_to_membership_id) REFERENCES project_membership(id)
);