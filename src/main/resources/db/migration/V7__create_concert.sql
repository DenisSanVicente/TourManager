CREATE TABLE concert (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artistic_project_id BIGINT NOT NULL,
    venue_id BIGINT,
    tour_id BIGINT,
    referent_membership_id BIGINT,
    title VARCHAR(150) NOT NULL,
    concert_date TIMESTAMP NOT NULL,
    status VARCHAR(50) NOT NULL,
    notes TEXT,
    archived BOOLEAN NOT NULL DEFAULT FALSE,

    FOREIGN KEY (artistic_project_id)
        REFERENCES artistic_project(id),

    FOREIGN KEY (venue_id)
        REFERENCES venue(id),

    FOREIGN KEY (tour_id)
        REFERENCES tour(id),

    FOREIGN KEY (referent_membership_id)
        REFERENCES project_membership(id)
);
