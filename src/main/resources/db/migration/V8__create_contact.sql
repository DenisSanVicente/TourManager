CREATE TABLE contact (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT,
    artistic_project_id BIGINT NOT NULL,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    job_title VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(25),
    notes TEXT,

    FOREIGN KEY (venue_id)
        REFERENCES venue(id),

    FOREIGN KEY (artistic_project_id)
        REFERENCES artistic_project(id)
);