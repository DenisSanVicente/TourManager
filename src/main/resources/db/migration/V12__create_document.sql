
CREATE TABLE document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    file_path VARCHAR(500) NOT NULL,
    file_type VARCHAR(100) NOT NULL,
    uploaded_at TIMESTAMP NOT NULL,
    artistic_project_id BIGINT NOT NULL,
    concert_id BIGINT,
    tour_id BIGINT,
    uploaded_by_membership_id BIGINT NOT NULL,

    FOREIGN KEY (artistic_project_id)
        REFERENCES artistic_project(id),

    FOREIGN KEY (concert_id)
        REFERENCES concert(id),

    FOREIGN KEY (tour_id)
        REFERENCES tour(id),

    FOREIGN KEY (uploaded_by_membership_id)
        REFERENCES project_membership(id)
);
