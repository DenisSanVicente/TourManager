CREATE TABLE financial_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(255) NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    entry_type VARCHAR(20) NOT NULL,
    category VARCHAR(50) NOT NULL,
    entry_date DATE NOT NULL,
    artistic_project_id BIGINT NOT NULL,
    concert_id BIGINT,
    tour_id BIGINT,
    paid_by_membership_id BIGINT,

    FOREIGN KEY (artistic_project_id) REFERENCES artistic_project(id),
    FOREIGN KEY (concert_id) REFERENCES concert(id),
    FOREIGN KEY (tour_id) REFERENCES tour(id),
    FOREIGN KEY (paid_by_membership_id) REFERENCES project_membership(id)
);