
CREATE TABLE project_invitation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artistic_project_id BIGINT NOT NULL,
    invited_user_id BIGINT,
    invited_by_membership_id BIGINT NOT NULL,
    invited_email VARCHAR(250) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    responded_at TIMESTAMP,
    token_hash VARCHAR(255) NOT NULL,

    FOREIGN KEY (artistic_project_id)
        REFERENCES artistic_project(id),

    FOREIGN KEY (invited_user_id)
        REFERENCES app_user(id),

    FOREIGN KEY (invited_by_membership_id)
        REFERENCES project_membership(id)
);
