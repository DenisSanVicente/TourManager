CREATE TABLE tour (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artistic_project_id BIGINT NOT NULL,
    referent_membership_id BIGINT,
    name VARCHAR(150) NOT NULL,
    start_date DATE,
    end_date DATE,
    status VARCHAR(30) NOT NULL,
    description TEXT,
    archived BOOLEAN NOT NULL DEFAULT FALSE,

    FOREIGN KEY (artistic_project_id)
        REFERENCES artistic_project(id),

    FOREIGN KEY (referent_membership_id)
        REFERENCES project_membership(id),

    CONSTRAINT chk_tour_dates
        CHECK (
            start_date IS NULL
            OR end_date IS NULL
            OR end_date >= start_date
        )
);
